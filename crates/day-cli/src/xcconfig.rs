//! The `DayApp.xcconfig` split (§17.4): user-adjustable Xcode build settings live in a
//! committed `DayApp.xcconfig` beside each `DayApp.xcodeproj`, and the Day.toml-derived
//! identity (bundle id, version, build number) is written to a gitignored
//! `build/day/xcconfig/<platform>.xcconfig` that the committed file `#include?`s after its
//! own settings, so Day.toml stays authoritative once `day build` has run, while a fresh
//! checkout still builds in the Xcode IDE from the committed fallback lines. A second
//! `#include?` follows it for `DayApp.local.xcconfig`, the gitignored per-checkout file
//! carrying a developer's signing team and anything else that should not be committed.
//! Being last, it overrides even the generated identity, which is what a device
//! provisioning profile issued for another bundle id needs. Precedence still ends at the
//! command line: the settings `day build`/`day pack` pass to xcodebuild override all three.
use crate::meta::Project;
fn target_for(platform: &str) -> &'static str {
    if platform == "macos" {
        "macos-appkit"
    } else {
        "ios-uikit"
    }
}

/// The deployment target the committed `platform/<platform>/DayApp.xcconfig` declares
/// (`MACOSX_DEPLOYMENT_TARGET = 13.0`, `IPHONEOS_DEPLOYMENT_TARGET = 15.0`), or `None` when
/// the file or the line is absent. What
/// the cargo half of an Apple build hands its C compilers, so every object targets the same
/// floor the Xcode link does.
pub fn deployment_target(project: &Project, platform: &str) -> Option<String> {
    let key = if platform == "macos" {
        "MACOSX_DEPLOYMENT_TARGET"
    } else {
        "IPHONEOS_DEPLOYMENT_TARGET"
    };
    let path = project
        .root
        .join("platform")
        .join(platform)
        .join("DayApp.xcconfig");
    let text = std::fs::read_to_string(path).ok()?;
    text.lines()
        .map(str::trim)
        .filter(|l| !l.starts_with("//"))
        .find_map(|l| {
            let (k, v) = l.split_once('=')?;
            (k.trim() == key).then(|| v.trim().to_string())
        })
        .filter(|v| !v.is_empty())
}

/// Write `build/day/xcconfig/<platform>.xcconfig`, the Day-managed values the committed
/// `DayApp.xcconfig` includes last. Rewritten (when changed) on every build so the bundle
/// id, version, and build number always track Day.toml.
pub fn write_generated(project: &Project, platform: &str) -> Result<(), String> {
    let resolved = project.manifest.resolve(target_for(platform));
    let win = &project.manifest.window;
    // Day.toml `[window]`'s minimum rides here as a build setting, and the checked-in Info.plist
    // references it as `$(DAY_WINDOW_MIN_WIDTH)`, the same mechanism `DAY_URL_SCHEME` above has
    // always used. day-uikit reads the resolved numbers back out of the built bundle and applies
    // them to `UIWindowScene.sizeRestrictions` (docs/screenshots.md, docs/size-classes.md).
    //
    // Not written into the plist, which is where this started. That file is tracked, so a build
    // that rewrites it leaves the working tree dirty and CI refuses to pack from it, and every
    // later edit to `[window]` would dirty it again. `INFOPLIST_KEY_*` is not the alternative
    // either: those apply only when Xcode generates the plist, and the scaffold ships a real one
    // (`GENERATE_INFOPLIST_FILE = NO`). Variable substitution is, and it costs the plist one
    // stable reference instead of a value that goes stale.
    let mut out = format!(
        "// Generated by `day build` from Day.toml — do not edit (change Day.toml [app],\n\
         // Day.toml [window] or Cargo.toml [package] instead). platform/{platform}/DayApp.xcconfig\n\
         // includes this last.\n\
         PRODUCT_BUNDLE_IDENTIFIER = {}\n\
         MARKETING_VERSION = {}\n\
         CURRENT_PROJECT_VERSION = {}\n\
         DAY_APP_TITLE = {}\n\
         DAY_URL_SCHEME = {}\n\
         DAY_WINDOW_MIN_WIDTH = {}\n\
         DAY_WINDOW_MIN_HEIGHT = {}\n",
        resolved.id,
        resolved.version,
        resolved.build,
        // The name on the home screen, which the checked-in Info.plist takes as
        // `$(DAY_APP_TITLE)`. Baked into that file at scaffold time until 2026-09, so an app
        // that renamed itself in Day.toml kept the old name on Apple platforms — and a build
        // flavor, whose whole business is a different name, could not change it at all
        // (docs/flavors.md). `day lint` migrates a plist that still pins the literal.
        resolved.title,
        resolved.scheme(),
        win.min_width.round() as i64,
        win.min_height.round() as i64,
    );
    if platform == "macos" {
        for (name, profile) in [
            ("Debug", crate::cli::Profile::Debug),
            ("Release", crate::cli::Profile::Release),
        ] {
            let path = crate::sandbox::entitlements(project, profile)?;
            out.push_str(&format!(
                "CODE_SIGN_ENTITLEMENTS[config={name}] = {}\n",
                path.as_ref()
                    .map(|p| p.display().to_string())
                    .unwrap_or_default()
            ));
        }
        if let Some(config) = &project.manifest.sandbox.macos_appkit {
            out.push_str(&format!(
                "ENABLE_APP_SANDBOX = {}\n",
                if config.enabled { "YES" } else { "NO" }
            ));
            if config.enabled {
                out.push_str("CODE_SIGNING_ALLOWED = YES\n");
                out.push_str("CODE_SIGN_INJECT_BASE_ENTITLEMENTS[config=Release] = NO\n");
            }
        }
    }
    let dir = project.root.join("build/day/xcconfig");
    std::fs::create_dir_all(&dir).map_err(|e| format!("mkdir {}: {e}", dir.display()))?;
    let path = dir.join(format!("{platform}.xcconfig"));
    if std::fs::read_to_string(&path).ok().as_deref() != Some(out.as_str()) {
        std::fs::write(&path, out).map_err(|e| format!("{}: {e}", path.display()))?;
    }
    Ok(())
}
