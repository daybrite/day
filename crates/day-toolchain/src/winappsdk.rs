fn walk(base: &Path, dir: &Path, f: &mut dyn FnMut(&Path, &Path)) -> Result<(), String> {
    let entries = std::fs::read_dir(dir).map_err(|e| format!("reading {}: {e}", dir.display()))?;
    for e in entries.flatten() {
        let p = e.path();
        if p.is_dir() {
            walk(base, &p, f)?;
        } else if let Ok(rel) = p.strip_prefix(base) {
            f(&p, rel);
        }
    }
    Ok(())
}

// A fragment is small, machine-written XML with no nesting of the elements read here, so a
// scan is enough and keeps this crate dependency-free.

/// Every `<tag …>…</tag>` element, as its full text.
fn elements<'a>(xml: &'a str, tag: &str) -> Vec<&'a str> {
    let (open, close) = (format!("<{tag}"), format!("</{tag}>"));
    let mut out = Vec::new();
    let mut rest = xml;
    while let Some(start) = rest.find(&open) {
        let after = &rest[start..];
        // `<ProxyStub` must not match `<ProxyStubX`.
        if !after[open.len()..].starts_with([' ', '>', '\r', '\n', '\t']) {
            rest = &after[open.len()..];
            continue;
        }
        let Some(end) = after.find(&close) else { break };
        out.push(&after[..end + close.len()]);
        rest = &after[end + close.len()..];
    }
    out
}

/// Every `<tag …>` or `<tag …/>` start tag.
fn start_tags<'a>(xml: &'a str, tag: &str) -> Vec<&'a str> {
    let open = format!("<{tag}");
    let mut out = Vec::new();
    let mut rest = xml;
    while let Some(start) = rest.find(&open) {
        let after = &rest[start..];
        let Some(end) = after.find('>') else { break };
        if after[open.len()..].starts_with([' ', '>', '/', '\r', '\n', '\t']) {
            out.push(&after[..=end]);
        }
        rest = &after[end + 1..];
    }
    out
}

fn element_text<'a>(xml: &'a str, tag: &str) -> Option<&'a str> {
    let open = format!("<{tag}>");
    let start = xml.find(&open)? + open.len();
    let end = xml[start..].find(&format!("</{tag}>"))?;
    Some(xml[start..start + end].trim())
}

fn attribute<'a>(tag: &'a str, name: &str) -> Option<&'a str> {
    let key = format!("{name}=\"");
    let start = tag.find(&key)? + key.len();
    let end = tag[start..].find('"')?;
    Some(&tag[start..start + end])
}

/// The include path for a piece's XAML shim (docs/winui.md "Pieces"): the SDK's cppwinrt
/// directory alone for `windows-xaml`, and for `windows-winui` (the piece's `winui` feature) the
/// generated Windows App SDK projection and headers AHEAD of it, since the projection shares that
/// directory's base.h. The shim picks its namespace aliases from `DAY_WINUI`, as day-xaml-sys does.
///
/// In a build script: `.includes(shim_includes(&cppwinrt))` where it used to add `cppwinrt`, and
/// `if shim_is_winui() { build.define("DAY_WINUI", None); }` before compiling.
pub fn shim_includes(cppwinrt_include: &Path) -> Vec<PathBuf> {
    if !shim_is_winui() {
        return vec![cppwinrt_include.to_path_buf()];
    }
    let arch = std::env::var("CARGO_CFG_TARGET_ARCH").unwrap_or_default();
    let sdk = resolve_for_build_script(cppwinrt_include, &arch)
        .unwrap_or_else(|e| panic!("the Windows App SDK (winui): {e}"));
    let mut includes = vec![sdk.projection];
    includes.extend(sdk.includes);
    includes.push(cppwinrt_include.to_path_buf());
    includes
}

/// Whether this build script is compiling for `windows-winui`: the crate's `winui` feature.
pub fn shim_is_winui() -> bool {
    std::env::var("CARGO_FEATURE_WINUI").is_ok()
}

/// [`resolve`] for build scripts: also emits the `rerun-if-env-changed` lines.
pub fn resolve_for_build_script(
    cppwinrt_include: &Path,
    target_arch: &str,
) -> Result<WinAppSdk, String> {
    for var in ["DAY_WINAPPSDK", "DAY_WINAPPSDK_CACHE"] {
        println!("cargo:rerun-if-env-changed={var}");
    }
    resolve(cppwinrt_include, target_arch)
}

/// The SDK's `cppwinrt.exe` next to `Include\<version>`: `bin\<version>\<host arch>`.
fn cppwinrt_exe(cppwinrt_include: &Path, sdk_version: &str) -> Result<PathBuf, String> {
    let kits = cppwinrt_include
        .parent()
        .and_then(Path::parent)
        .and_then(Path::parent)
        .ok_or_else(|| {
            format!(
                "{} is not under a Windows Kits root",
                cppwinrt_include.display()
            )
        })?;
    let hosts: &[&str] = if cfg!(target_arch = "aarch64") {
        &["arm64", "x64", "x86"]
    } else {
        &["x64", "x86"]
    };
    for host in hosts {
        let exe = kits
            .join("bin")
            .join(sdk_version)
            .join(host)
            .join("cppwinrt.exe");
        if exe.exists() {
            return Ok(exe);
        }
    }
    Err(format!(
        "no cppwinrt.exe for Windows SDK {sdk_version} under {}",
        kits.join("bin").display()
    ))
}

/// Make `<root>/<id>.<version>` hold the extracted package: the NuGet global cache's copy if the
/// machine has one, else a download from nuget.org.
fn fetch_package(root: &Path, id: &str, version: &str) -> Result<(), String> {
    let _package_lock = cache_lock(root, &format!("{id}.{version}"))?;
    let dest = root.join(format!("{id}.{version}"));
    if dest.join(".complete").exists() {
        return Ok(());
    }
    std::fs::create_dir_all(root).map_err(|e| format!("creating {}: {e}", root.display()))?;
    let staging = root.join(format!("{id}.{version}.partial"));
    let _ = std::fs::remove_dir_all(&staging);
    std::fs::create_dir_all(&staging)
        .map_err(|e| format!("creating {}: {e}", staging.display()))?;

    let nuget_cache = std::env::var("NUGET_PACKAGES")
        .map(PathBuf::from)
        .or_else(|_| {
            std::env::var("USERPROFILE").map(|h| PathBuf::from(h).join(".nuget").join("packages"))
        })
        .ok()
        .map(|p| p.join(id).join(version))
        .filter(|p| p.is_dir());
    if let Some(src) = nuget_cache {
        copy_dir(&src, &staging).map_err(|e| format!("copying {}: {e}", src.display()))?;
    } else {
        // A .nupkg is an OPC zip, which the in-box bsdtar extracts.
        let nupkg = root.join(format!("{id}.{version}.nupkg"));
        let url =
            format!("https://api.nuget.org/v3-flatcontainer/{id}/{version}/{id}.{version}.nupkg");
        run("curl", &["-sSfL", "-o", &nupkg.to_string_lossy(), &url])?;
        run(
            "tar",
            &[
                "-xf",
                &nupkg.to_string_lossy(),
                "-C",
                &staging.to_string_lossy(),
            ],
        )?;
        let _ = std::fs::remove_file(&nupkg);
    }
    std::fs::write(staging.join(".complete"), b"").map_err(|e| e.to_string())?;
    let _ = std::fs::remove_dir_all(&dest);
    std::fs::rename(&staging, &dest).map_err(|e| format!("publishing {}: {e}", dest.display()))
}

fn copy_dir(from: &Path, to: &Path) -> std::io::Result<()> {
    std::fs::create_dir_all(to)?;
    for entry in std::fs::read_dir(from)? {
        let entry = entry?;
        let target = to.join(entry.file_name());
        if entry.file_type()?.is_dir() {
            copy_dir(&entry.path(), &target)?;
        } else {
            std::fs::copy(entry.path(), target)?;
        }
    }
    Ok(())
}

// The OS releases the lock if a build script exits or crashes. Keep the lock file:
// deleting it would let another process lock a different file at the same path.
fn cache_lock(root: &Path, name: &str) -> Result<std::fs::File, String> {
    std::fs::create_dir_all(root).map_err(|e| format!("creating {}: {e}", root.display()))?;
    let path = root.join(format!("{name}.lock"));
    let file = std::fs::OpenOptions::new()
        .create(true)
        .truncate(false)
        .read(true)
        .write(true)
        .open(&path)
        .map_err(|e| format!("opening {}: {e}", path.display()))?;
    file.lock()
        .map_err(|e| format!("locking {}: {e}", path.display()))?;
    Ok(file)
}

fn run(cmd: &str, args: &[&str]) -> Result<(), String> {
    let out = Command::new(cmd)
        .args(args)
        .output()
        .map_err(|e| format!("running {cmd}: {e}"))?;
    if out.status.success() {
        Ok(())
    } else {
        Err(format!(
            "{cmd} {} failed: {}",
            args.join(" "),
            String::from_utf8_lossy(&out.stderr).trim()
        ))
    }
}

