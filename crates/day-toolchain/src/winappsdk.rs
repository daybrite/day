    #[test]
    fn cache_publishers_are_serialized() {
        let root = std::env::temp_dir().join(format!(
            "day-winappsdk-lock-{}-{}",
            std::process::id(),
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .unwrap()
                .as_nanos()
        ));
        std::fs::create_dir_all(&root).unwrap();
        std::fs::write(root.join("count"), "0").unwrap();
        std::thread::scope(|scope| {
            for _ in 0..8 {
                let root = &root;
                scope.spawn(move || {
                    for _ in 0..10 {
                        let _lock = cache_lock(root, "package").unwrap();
                        let count: usize = std::fs::read_to_string(root.join("count"))
                            .unwrap()
                            .parse()
                            .unwrap();
                        std::thread::yield_now();
                        std::fs::write(root.join("count"), (count + 1).to_string()).unwrap();
                    }
                });
            }
        });
        assert_eq!(std::fs::read_to_string(root.join("count")).unwrap(), "80");
        std::fs::remove_dir_all(root).unwrap();
    }

