import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

/** Generate symbolic accessors for website UI text. Publication text stays in content files. */
export async function generateSiteStrings({ check = false } = {}) {
  const catalog = JSON.parse(await readFile(new URL('../src/locales/en.json', import.meta.url), 'utf8'));
  const entries = Object.entries(catalog).sort(([a], [b]) => a.localeCompare(b));
  for (const [key, value] of entries) {
    if (!/^[a-z][a-z0-9_]*$/.test(key) || typeof value !== 'string') {
      throw new Error(`Invalid website translation: ${key}`);
    }
  }
  const output = '// Generated by scripts/generate-site-strings.mjs. Edit src/locales/en.json.\n' +
    '// Copyright © The Daybrite Project\n// SPDX-License-Identifier: CC-BY-SA-4.0\n' +
    'export const res = {\n  str: {\n' +
    entries.map(([key, value]) => `    ${key}: () => ${JSON.stringify(value)},`).join('\n') +
    '\n  },\n};\n';
  const destination = new URL('../src/generated/strings.mjs', import.meta.url);
  const previous = await readFile(destination, 'utf8').catch(() => '');
  if (previous === output) return;
  if (check) throw new Error('Website strings are stale; run npm run strings:generate');
  await mkdir(new URL('../src/generated/', import.meta.url), { recursive: true });
  await writeFile(destination, output);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await generateSiteStrings({ check: process.argv.includes('--check') });
}
