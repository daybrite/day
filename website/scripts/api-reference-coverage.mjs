import { createMarkdownProcessor, parseFrontmatter } from '@astrojs/markdown-remark';

// Detect callable syntax, never choose a destination from a method's spelling alone.
// Bare names without call syntax are editorially ambiguous (fields, CLI verbs, CSS, etc.).
export function callableNames(text, names) {
  if (/^(?:#\!?\[|@|--)/.test(text)) return [];
  const tokens = [...text.matchAll(/(?<![\w:])(?:[A-Za-z_]\w*::)*[a-z_]\w*(?=\s*(?:::<[^()]+>)?\s*\()/g)].map(m => m[0]);
  if (/^\.[a-z_]\w*(?:\s*\/\s*\.[a-z_]\w*)*$/.test(text)) {
    tokens.push(...text.split(/\s*\/\s*/).map(token => token.slice(1)));
  }
  if (/^(?:[A-Za-z_]\w*::)+[a-z_]\w*$/.test(text)) tokens.push(text);
  return [...new Set(tokens.filter(token => {
    // These are generated by the consuming application, not published Day API items.
    if (/^(?:crate::)?res::/.test(token) && !/^res::str::day_/.test(token)) return false;
    return names.has(token.split('::').at(-1));
  }))];
}

export async function unlinkedReferences(source, names) {
  const references = [];
  const { content } = parseFrontmatter(source, { frontmatter: 'empty-with-lines' });
  const processor = await createMarkdownProcessor({
    syntaxHighlight: false, smartypants: false,
    remarkPlugins: [() => tree => {
      const definitions = new Set();
      function collect(node) {
        if (node.type === 'definition') definitions.add(node.identifier);
        for (const child of node.children ?? []) collect(child);
      }
      collect(tree);
      function visit(node, linked = false) {
        if (['code', 'html'].includes(node.type)) return;
        linked ||= node.type === 'link' ||
          (node.type === 'linkReference' && definitions.has(node.identifier));
        if (node.type === 'inlineCode' && !linked) {
          const functions = callableNames(node.value, names);
          if (functions.length) references.push({ line: node.position.start.line, code: node.value, functions });
        }
        for (const child of node.children ?? []) visit(child, linked);
      }
      visit(tree);
    }],
  });
  await processor.render(content);
  return references;
}
