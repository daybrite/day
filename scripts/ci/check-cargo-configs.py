"""Reject machine-local Cargo overrides in files that Git would publish."""

from pathlib import Path, PurePosixPath, PureWindowsPath
import subprocess
import sys
import tomllib


def check(root):
    names = subprocess.check_output(
        ["git", "ls-files", "--cached", "--others", "--exclude-standard", "-z"],
        cwd=root,
    ).decode().split("\0")
    errors = []
    for name in sorted(set(filter(None, names))):
        path = root / name
        if path.parent.name != ".cargo" or path.name not in ("config", "config.toml"):
            continue
        if not path.exists():  # An unstaged deletion is a valid working-tree repair.
            continue
        source = path.read_text()
        if source.startswith("# Generated by `day patch`"):
            errors.append(f"{name}: generated day patch configuration must stay untracked")
            continue
        try:
            config = tomllib.loads(source)
        except tomllib.TOMLDecodeError as error:
            errors.append(f"{name}: {error}")
            continue
        tables = list(config.get("patch", {}).values()) + [config.get("replace", {})]
        for table in tables:
            for package, spec in table.items():
                value = spec.get("path") if isinstance(spec, dict) else None
                if isinstance(value, str) and (
                    PurePosixPath(value).is_absolute() or PureWindowsPath(value).anchor
                ):
                    errors.append(f"{name}: {package} uses a machine-specific path: {value}")
    return errors


if __name__ == "__main__":
    errors = check(Path(__file__).resolve().parents[2])
    if errors:
        print("\n".join(errors), file=sys.stderr)
        sys.exit(1)
    print("Cargo configurations: no publishable machine-local overrides")
