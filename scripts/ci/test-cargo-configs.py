"""Check Cargo override portability without committing any fixture."""

import importlib.util
import os
from pathlib import Path
import subprocess
import tempfile
import unittest


spec = importlib.util.spec_from_file_location(
    "cargo_configs", Path(__file__).with_name("check-cargo-configs.py")
)
checker = importlib.util.module_from_spec(spec)
spec.loader.exec_module(checker)


class CargoConfigTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix="day-cargo-configs-")
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.env = {key: value for key, value in os.environ.items() if not key.startswith("GIT_")}
        self.git("init", "-q")
        self.config = self.root / "apps/demo/.cargo/config.toml"
        self.config.parent.mkdir(parents=True)

    def git(self, *args):
        subprocess.run(["git", *args], cwd=self.root, env=self.env, check=True, capture_output=True)

    def test_absolute_patch_paths_fail_on_every_host(self):
        for value in ("/opt/src/framework", "C:/src/framework", r"C:\src\framework"):
            with self.subTest(value=value):
                self.config.write_text(f"[patch.crates-io]\nday-app = {{ path = '{value}' }}\n")
                self.assertIn("machine-specific path", "\n".join(checker.check(self.root)))

    def test_portable_configuration_passes(self):
        self.config.write_text('[build]\ntarget = "wasm32-unknown-unknown"\n'
                               '[patch.crates-io]\nexample = { path = "../example" }\n')
        self.assertEqual(checker.check(self.root), [])

    def test_ignored_override_is_local_but_tracked_override_fails(self):
        self.config.write_text('# Generated by `day patch` — machine-local\n[patch.crates-io]\n')
        (self.root / ".gitignore").write_text("/apps/*/.cargo/config.toml\n")
        self.assertEqual(checker.check(self.root), [])
        self.git("add", "--force", "apps/demo/.cargo/config.toml")
        self.assertIn("must stay untracked", "\n".join(checker.check(self.root)))
        self.config.unlink()
        self.assertEqual(checker.check(self.root), [])

    def test_legacy_config_and_replacement_are_checked(self):
        self.config = self.config.with_name("config")
        self.config.write_text('[replace]\n"example:0.1.0" = { path = "/tmp/example" }\n')
        self.assertTrue(checker.check(self.root))


if __name__ == "__main__":
    unittest.main()
